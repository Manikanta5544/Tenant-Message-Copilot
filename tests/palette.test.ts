import { describe, expect, it } from "vitest";
import { isPaletteKey, rank } from "../app/lib/palette";
import { reviewLine } from "../app/components/ReviewHistory";

const items = [{ label: "Inbox" }, { label: "Evals", keywords: "tests scores" }, { label: "Ravi Menon, B-204", hint: "My rent shows 12,000 due" }, { label: "Asha Rao, A-101", hint: "Is the pool open", keywords: "Scenario 2" }, { label: "Toggle theme", keywords: "dark light" }];

describe("command palette ranking", () => {
  it("returns everything for an empty query and filters by every word", () => {
    expect(rank(items, "")).toHaveLength(5);
    expect(rank(items, "rent due").map((x) => x.label)).toEqual(["Ravi Menon, B-204"]);
    expect(rank(items, "zzz")).toEqual([]);
  });
  it("finds by name, unit, message text and keywords; label matches outrank hint matches", () => {
    expect(rank(items, "b-204")[0]!.label).toContain("Ravi");
    expect(rank(items, "pool")[0]!.label).toContain("Asha");
    expect(rank(items, "dark")[0]!.label).toBe("Toggle theme");
    expect(rank(items, "scenario 2")[0]!.label).toContain("Asha");
    expect(rank([{ label: "Other", hint: "evals" }, { label: "Evals" }], "evals").map((x) => x.label)).toEqual(["Evals", "Other"]);
  });
  it("opens on Ctrl+K or Cmd+K only", () => {
    const k = (o: object) => isPaletteKey({ key: "k", ctrlKey: false, metaKey: false, altKey: false, shiftKey: false, ...o });
    expect(k({ ctrlKey: true })).toBe(true); expect(k({ metaKey: true })).toBe(true);
    expect(k({})).toBe(false); expect(k({ ctrlKey: true, shiftKey: true })).toBe(false); expect(k({ ctrlKey: true, key: "j" })).toBe(false);
  });
});

describe("review log wording", () => {
  const at = "2026-11-24T11:23:00.000Z"; // 16:53 in Asia/Calcutta
  const r = (action: "approved" | "edited" | "regenerated") => ({ id: "1", run_id: "r", action, edited_text: null, created_at: at }) as never;
  it("reads as a sentence about the person, with the time", () => {
    const hhmm = new Intl.DateTimeFormat("en-IN", { hour: "2-digit", minute: "2-digit", hour12: false }).format(new Date(at));
    expect(reviewLine(r("regenerated"))).toBe(`Draft regenerated by you at ${hhmm}`);
    expect(reviewLine(r("approved"))).toBe(`Approved by you at ${hhmm}`);
    expect(reviewLine(r("edited"), "3 words changed")).toBe(`Edited by you at ${hhmm}: 3 words changed`);
  });
});
